// Lessons for the procedures trainer. Each step either ticks itself off when the aircraft is in the
// right state, or (manual steps) waits for the learner to press Next after reading.
//
// Written in our own words as simplified training flows for the A320 family, from general public
// knowledge. They are not airline or manufacturer procedures. Real crews follow their operator's
// approved checklists. A type-rated pilot should review these before anyone learns from them.
import type { FcuAction } from "../sim/fcc";
import type { Switches } from "../sim/systems";
import type { A320Extras, Controls, SimState } from "../sim/types";
import type { FmsData } from "../cockpit/mcdu";
import type { EfisState } from "../cockpit/efis";
import type { LessonBase, StepBase } from "./types";
import { DETENT } from "../cockpit/levers";
import type { Clearance } from "../radio/radioBox";

export type PanelName = "ovhd" | "main" | "ped";

export type LessonStep = StepBase<SimState, Controls, FmsData, PanelName>;

export interface Lesson extends LessonBase<SimState, Controls, FmsData, PanelName> {
  /** Start position id from config.ts. */
  startId: string;
  /** Changes to the starting switch positions. */
  switches?: (sw: Switches) => void;
  /** FCU actions sent once the aircraft is placed (for example engaging the autopilot). */
  fcuActions?: FcuAction[];
  /** MCDU entries already made when the lesson starts. */
  fms?: Partial<FmsData>;
  /** EFIS settings at the start (flight director, baro). */
  efis?: Partial<EfisState>;
  /** Today's QNH in hPa. The altimeter shows true altitude when the baro is set to it. */
  qnh?: number;
  /** Pedestal and cockpit settings at the start (trims, spoilers, autobrake, ECAM page). */
  extras?: Partial<A320Extras>;
  /** GEN 1 fails this many seconds after the lesson starts. */
  failAfterS?: number;
  /** ATC clearance given on the delivery or ground frequency. */
  clearance?: Clearance;
  /** Our callsign on the radio. */
  callsign?: string;
  /** Fuel in the left wing, centre and right wing tanks at the start, kg. */
  tanksKg?: [number, number, number];
}

