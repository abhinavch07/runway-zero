// PA-28 lessons. Simplified training flows for a carburettor PA-28 with a glass cockpit, written in
// our own words from general public knowledge. Not the manufacturer's checklist: real pilots use
// the POH and their school's checklist. A flight instructor should review these.
// The radio and VOR/ILS lessons are the C172 ones with the PA-28 callsign.
import { C172_LESSONS, type C172Lesson } from "./lessons";
import type { C172State } from "./sim/types";

const rpmBetween = (s: C172State, lo: number, hi: number) => s.engine.running && s.engine.rpm >= lo && s.engine.rpm <= hi;
const CALLSIGN = "VT-RZP";

/** A C172 lesson reused for the PA-28, with a new id and the PA-28 callsign in every text. */
function reuse(fromId: string, id: string): C172Lesson {
  const from = C172_LESSONS.find((l) => l.id === fromId)!;
  const swap = (t: string) => t.replaceAll("VT-RZA", CALLSIGN);
  return {
    ...from,
    id,
    callsign: CALLSIGN,
    clearance: from.clearance && {
      ...from.clearance,
      atc: swap(from.clearance.atc),
      readbacks: from.clearance.readbacks.map(swap) as [string, string, string],
    },
  };
}

