import { readFileSync } from "node:fs";
import { JSBSimSdk } from "@0x62/jsbsim-wasm";
import { MODEL_FILES, STEP_HZ } from "../src/sim/core.ts";
const root = new URL("../public/jsbsim/", import.meta.url);
const w = new URL("../node_modules/@0x62/jsbsim-wasm/dist/wasm/", import.meta.url);
const sdk = await JSBSimSdk.create({ moduleUrl: new URL("jsbsim_wasm.mjs", w), wasmUrl: new URL("jsbsim_wasm.wasm", w), log: { console: false } });
for (const f of MODEL_FILES) sdk.writeDataFile(f, readFileSync(new URL(f, root), "utf8"));
sdk.configurePaths({ aircraftPath: "aircraft", enginePath: "engine", systemsPath: "systems" });
sdk.loadModel("A320"); sdk.setDt(1 / STEP_HZ);
const s = (p: string, v: number) => sdk.setPropertyValue(p, v), g = (p: string) => sdk.getPropertyValue(p);
for (const [k, v] of Object.entries({ "ic/lat-geod-deg": 28.56, "ic/long-gc-deg": 77.12, "ic/terrain-elevation-ft": 778, "ic/h-agl-ft": 7.2, "ic/vc-kts": 0, "ic/psi-true-deg": 285 })) s(k, v);
sdk.runIc();
s("gear/gear-cmd-norm", 1); s("gear/gear-pos-norm", 1);
const show = (t: number) => console.log(`t=${t.toFixed(0).padStart(3)} E1 n2=${g("propulsion/engine[0]/n2").toFixed(1).padStart(5)} n1=${g("propulsion/engine[0]/n1").toFixed(1).padStart(5)} egt=${g("propulsion/engine[0]/egt-degC").toFixed(0).padStart(4)} ff=${(g("propulsion/engine[0]/fuel-flow-rate-pps")*3600).toFixed(0).padStart(5)}pph run=${g("propulsion/engine[0]/set-running")} | E2 n2=${g("propulsion/engine[1]/n2").toFixed(1)} run=${g("propulsion/engine[1]/set-running")}`);
const engCmd = (i: number, starter: number, cutoff: number) => { s("propulsion/active_engine", i); s("propulsion/starter_cmd", starter); s("propulsion/cutoff_cmd", cutoff); };
let t = 0;
const run = (sec: number, each: () => void, every = 5) => { for (let k = 0; k < sec * STEP_HZ; k++) { each(); sdk.run(); t += 1 / STEP_HZ; if (k % (every * STEP_HZ) === 0) show(t); } };
show(0);
console.log("-- engine 1: starter on, fuel off until N2 22%");
run(60, () => { const n2 = g("propulsion/engine[0]/n2"); const running = g("propulsion/engine[0]/set-running") > 0; engCmd(0, running ? 0 : 1, n2 >= 22 || running ? 0 : 1); engCmd(1, 0, 1); }, 5);
console.log("-- engine 1 master off");
run(30, () => { engCmd(0, 0, 1); engCmd(1, 0, 1); }, 10);
